const currentImages = {};

function changeImage(sliderId, direction) {
    const images = sliders[sliderId];

    currentImages[sliderId] = currentImages[sliderId] ?? 0;

    currentImages[sliderId] =
        (currentImages[sliderId] + direction + images.length) % images.length;

    const image = images[currentImages[sliderId]];
    const element = document.getElementById(sliderId);

    element.src = image.src;
    element.alt = image.alt;
}